"""File-based CLI: never executes It, a model, server or agent process."""
import argparse
import json
import sys
from pathlib import Path

from .core import (ROOT, KEYS, OwlPilotError, initial_state, handle_action, complete_guide,
                   guide_context, unpack_state, check_budget, encoded, prepare_material, fail_request)


def load(path):
    def reject_constant(value):
        raise OwlPilotError(f"Nonfinite JSON value {value} is invalid.")
    try:
        p = Path(path)
        if p.stat().st_size > 2 * 1024 * 1024:
            raise OwlPilotError("JSON input is too large (maximum 2 MiB).")
        return json.loads(p.read_text(encoding="utf-8"), parse_constant=reject_constant)
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise OwlPilotError(f"Cannot read valid JSON from {path}: {exc}") from exc


def write_output(path, value):
    p = Path(path)
    # Writes only the explicit caller-selected output; refuses symlinks and existing files.
    if p.is_symlink() or p.exists():
        raise OwlPilotError("Output already exists; use a new patch/context filename.")
    p.parent.mkdir(parents=True, exist_ok=True)
    if p.parent.is_symlink():
        raise OwlPilotError("Output parent must not be a symlink.")
    with p.open("xb") as f:
        f.write(encoded(value) + b"\n")


def main(argv=None):
    parser = argparse.ArgumentParser(description="Prepare validated OwlPilot JSON state/merge patches. It owns persistence; this CLI never invokes It or a model.")
    sub = parser.add_subparsers(dest="command", required=True)
    init = sub.add_parser("initial", help="Write initial compact subject-independent It state.")
    init.add_argument("--agent", default="DeepSeek Harness", help="Display label, not a model connection or runner.")
    init.add_argument("--out", required=True, help="New JSON output path.")
    handle = sub.add_parser("handle", help="Validate a saved It action against current saved It state; write only a merge patch.")
    handle.add_argument("--state", required=True, help="Raw state or `it state` JSON wrapper.")
    handle.add_argument("--action", required=True, help="Saved {id,action,data} JSON.")
    handle.add_argument("--out", required=True, help="New merge-patch filename; apply manually with it patch --if-revision.")
    handle.add_argument("--file", help="Explicit supervised local path of a saved It attachment, for import_file only. Action-supplied paths are ignored.")
    handle.add_argument("--proposals", help="JSON list of supplied source-based candidates; never generated by this helper.")
    context = sub.add_parser("context", help="Write source-grounded context for a configured supervised agent, without invoking a model.")
    context.add_argument("--state", required=True)
    context.add_argument("--course", required=True)
    context.add_argument("--request", help="Optional existing running guide reservation ID.")
    context.add_argument("--out", required=True)
    complete = sub.add_parser("complete", help="Validate supplied agent guide JSON against its running reservation, produce checked patch.")
    complete.add_argument("--state", required=True)
    complete.add_argument("--request", required=True)
    complete.add_argument("--result", required=True)
    complete.add_argument("--out", required=True)
    failure = sub.add_parser("fail", help="Explicitly mark an interrupted running guide failed; never retries a model.")
    failure.add_argument("--state", required=True)
    failure.add_argument("--request", required=True)
    failure.add_argument("--reason", required=True)
    failure.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    try:
        if args.command == "initial":
            state = initial_state(args.agent)
            check_budget(state)
            write_output(args.out, state)
            summary = {"status": "initial", "statePath": str(Path(args.out).resolve()), "domainRevision": 0}
        elif args.command == "context":
            result = guide_context(load(args.state), args.course, args.request)
            write_output(args.out, result)
            summary = {"status": "context", "contextPath": str(Path(args.out).resolve()), "courseId": args.course, "requestId": args.request}
        else:
            if args.command == "handle":
                result = handle_action(load(args.state), load(args.action), root=ROOT, file_path=args.file,
                                       proposals=load(args.proposals) if args.proposals else None)
            elif args.command == "fail":
                result = fail_request(load(args.state), args.request, args.reason)
            else:
                result = complete_guide(load(args.state), args.request, load(args.result))
            write_output(args.out, result["patch"])
            summary = {k: v for k, v in result.items() if k not in ("patch", "state", "context")}
            summary["patchPath"] = str(Path(args.out).resolve())
            summary["requiresItRevision"] = result["ifRevision"]
            if result["ifRevision"] is None:
                summary["warning"] = "Raw state has no It revision token. Read `it state` and inspect its revision before applying; do not apply unchecked."
            if "context" in result:
                summary["context"] = result["context"]
        print(json.dumps(summary, ensure_ascii=False, allow_nan=False))
        return 0
    except (OwlPilotError, OSError) as exc:
        print(json.dumps({"status": "rejected", "error": str(exc), "patchApplied": False}), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
